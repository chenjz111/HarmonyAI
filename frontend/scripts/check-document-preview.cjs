const { chromium } = require('playwright')
const { readFileSync, mkdirSync } = require('node:fs')
const { resolve } = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const output = resolve(__dirname, '../../artifacts/document-reference')
  mkdirSync(output, { recursive: true })
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
    await context.route('**/*', route => {
      const url = new URL(route.request().url())
      return ['127.0.0.1', 'localhost'].includes(url.hostname) || ['data:', 'blob:'].includes(url.protocol) ? route.continue() : route.abort()
    })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://127.0.0.1:5181/?harmonyai_demo=1#/pages/entry/entry')
    await page.locator('.choice-card').first().click()
    await page.getByText('点击上传文件', { exact: true }).waitFor()
    const start = page.getByRole('button', { name: '开始识别', exact: true })
    assert.equal(await start.isDisabled(), true, 'empty upload must be disabled')
    async function screenshots(name) {
      for (const width of [320, 390, 430, 900]) {
        await page.setViewportSize({ width, height: 844 })
        await page.screenshot({ path: resolve(output, `${name}-${width}.png`), fullPage: true })
        const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
        assert.equal(overflow, false, `${name} horizontal overflow at ${width}`)
      }
      await page.setViewportSize({ width: 390, height: 844 })
    }
    await screenshots('upload-empty')
    const fixture = readFileSync(resolve(__dirname, '../static/v31-home/nav-home.png'))
    async function pick(locator, names) {
      const event = page.waitForEvent('filechooser')
      await locator.click()
      await (await event).setFiles(names.map(name => ({ name, mimeType: 'image/png', buffer: fixture })))
    }
    await pick(page.getByText('点击上传文件', { exact: true }), ['demo-1.png'])
    assert.equal(await page.locator('.file-thumb').count(), 1)
    assert.equal(await start.isDisabled(), false)
    await pick(page.getByRole('button', { name: '添加资料' }), ['demo-2.png', 'demo-3.png'])
    assert.equal(await page.locator('.file-thumb').count(), 3)
    assert.equal(await page.getByRole('button', { name: '添加资料' }).count(), 0)
    await page.getByRole('button', { name: '删除第2张资料' }).click()
    assert.equal(await page.locator('.file-thumb').count(), 2)
    await pick(page.getByRole('button', { name: '添加资料' }), ['demo-4.png'])
    await screenshots('upload-selected')
    await start.click()
    await page.getByRole('button', { name: '资料摘要基本无误', exact: true }).waitFor({ timeout: 20000 })
    await screenshots('summary')
    const original = await page.locator('.summary-text').innerText()
    await page.getByRole('button', { name: '修改资料摘要', exact: true }).click()
    const editor = page.locator('textarea')
    await editor.waitFor()
    await page.waitForFunction(() => document.activeElement?.tagName === 'TEXTAREA')
    assert.equal(await editor.inputValue(), original)
    await editor.fill('这是本地演示编辑，取消后应恢复原摘要。')
    await screenshots('summary-edit')
    await page.getByRole('button', { name: '取消修改', exact: true }).click()
    assert.equal(await page.locator('.summary-text').innerText(), original)
    await page.getByRole('button', { name: '重新上传资料', exact: true }).click()
    await page.getByText('点击上传文件', { exact: true }).waitFor()
    await pick(page.getByText('点击上传文件', { exact: true }), ['demo-5.png'])
    await start.click()
    await page.getByRole('button', { name: '资料摘要基本无误', exact: true }).click({ timeout: 20000 })
    await page.waitForURL(url => url.hash.includes('v3-supplement'))
    await page.getByText('资料已整理完成', { exact: true }).waitFor({ timeout: 5000 })
    await screenshots('supplement')
    await page.getByRole('button', { name: '去填写问卷', exact: true }).click()
    await page.waitForURL(url => url.hash.includes('v3-questionnaire'))
    await page.getByText('下一题', { exact: true }).waitFor()
    await page.goto('http://127.0.0.1:5181/?harmonyai_demo=1#/pages/entry/entry')
    await page.locator('.choice-card').first().click()
    await page.getByText('点击上传文件', { exact: true }).waitFor()
    await pick(page.getByText('点击上传文件', { exact: true }), ['demo-save.png'])
    await start.click()
    await page.getByRole('button', { name: '修改资料摘要', exact: true }).click({ timeout: 20000 })
    await editor.fill('最近入睡偏慢，白天精神一般。')
    await page.getByRole('button', { name: '保存修改并继续', exact: true }).click()
    await page.waitForURL(url => url.hash.includes('v3-supplement'))
    await page.getByRole('button', { name: '直接进入分析', exact: true }).click()
    await page.waitForURL(url => url.hash.includes('v3-basis'))
    assert.deepEqual(errors, [])
    console.log('PASS: empty/upload 1-3/remove/add/manual recognition/summary edit focus/cancel/reupload/confirm route; responsive screenshots saved ' + output)
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
